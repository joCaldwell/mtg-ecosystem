#!/usr/bin/env node
// Real-input Maybe and reason-label checks against two disposable fixture servers.
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { UX_EVAL_ROOT } from './lib/paths.mjs';
import { chromium } from 'playwright-core';
import { BROWSER_ARGS, VIEWPORTS, newContext, watchPage, settle, scrollUntilVisible, axe } from './lib/browser.mjs';
const option = name => { const i = process.argv.indexOf('--' + name); return i < 0 ? undefined : process.argv[i + 1]; };
const root = UX_EVAL_ROOT, origin = option('origin') ?? 'http://127.0.0.1:8853', baseline = option('baseline') ?? 'http://127.0.0.1:8857', output = option('report') ?? join(root, 'manual', 'maybe-row-qa.json');
for (const url of [origin, baseline])
    assert.equal(new URL(url).hostname, '127.0.0.1', 'disposable fixture servers only');
mkdirSync(dirname(output), { recursive: true });
const api = async (path, method = 'GET', body, url = origin) => { const r = await fetch(url + path, { method, headers: { Cookie: 'uxeval_user=1', Origin: url, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) }); assert.equal(r.status, 200, method + ' ' + path); return r.json(); };
let state = (await api('/api/decks/2')).state;
const card = state.cards.find(c => c.maybe && c.mana_cost), other = state.cards.find(c => !c.maybe && c.role === 'card'), slots = state.slots.slice(0, 2).map(s => s.id);
assert.equal(slots.length, 2);
for (const url of [origin, baseline])
    await api('/api/decks/2/cards/' + card.oracle_id, 'PATCH', { slot_id: slots[0], secondary_slot_ids: [slots[1]], maybe_note: 'Consider with [[' + other.name + ']].' }, url);
const snap = s => ({ cards: s.cards.map(c => ({ id: c.oracle_id, maybe: c.maybe, slot: c.slot_id, secondary: c.secondary_slot_ids, tags: c.tag_ids, role: c.role, quantity: c.quantity, note: c.maybe_note })).sort((a, b) => a.id.localeCompare(b.id)), count: s.computed.card_count, maybe: s.computed.maybe_count });
const costless = state.cards.find(c => c.maybe && !c.mana_cost);
assert(costless, "fixture has a maybe card without a printed mana cost");
for (const url of [origin, baseline]) await api('/api/decks/2/cards/' + costless.oracle_id, 'PATCH', { maybe_note: 'Consider with [[' + other.name + ']].' }, url);
const snapshot = snap((await api('/api/decks/2')).state);
const browser = await chromium.launch({ args: BROWSER_ARGS }), results = [];
try {
    for (const width of [1280, 1440, 1920, 2560]) {
        const context = await newContext(browser, { origin, vp: VIEWPORTS[width], user: 1, frozenNow: '2026-10-20T17:00:00Z', notes: { blocked: new Set(), imageFailures: new Set() } }), page = await context.newPage(), watch = watchPage(page);
        await page.goto(origin + '/deck/2');
        await settle(page, watch);
        const section = page.getByRole('region', { name: 'Maybe list' }), row = section.locator('[data-oracle-id="' + card.oracle_id + '"]'), hit = row.getByRole('button', { name: card.name, exact: true });
        await scrollUntilVisible(page, row, VIEWPORTS[width]);
        assert.equal(await row.locator('[class*="_chip_"]').count(), 0);
        assert.equal(await row.locator('[class*="_purpose_"]').count(), 0);
        const close = async () => { const back = page.getByRole('button', { name: /Back/ }); if (await back.count())
            await back.click(); await settle(page, watch); };
        const checkOpen = async () => { await page.getByRole('heading', { name: card.name, exact: true }).waitFor(); assert.equal(await hit.getAttribute('aria-current'), 'true'); assert.equal(await page.getByText('Reviewing', { exact: true }).count(), 0); };
        const point = async (b) => page.mouse.click(b.x + b.width / 2, b.y + b.height / 2);
        let b = await row.boundingBox();
        await page.mouse.click(b.x + b.width * .7, b.y + b.height / 2);
        await settle(page, watch);
        await checkOpen();
        await close();
        const mana = row.locator('[class*="_cost_"]').first();
        await point(await mana.boundingBox());
        await settle(page, watch);
        await checkOpen();
        await close();
        const price = row.locator('[class*="_price_"]').last();
        await point(await price.boundingBox());
        await settle(page, watch);
        await checkOpen();
        await close();
        await hit.focus();
        await hit.press('Enter');
        await settle(page, watch);
        await checkOpen();
        await close();
        await hit.focus();
        await hit.press('Space');
        await settle(page, watch);
        await checkOpen();
        await close();
        await hit.focus();
        await page.keyboard.press('Tab');
        await page.keyboard.press('Shift+Tab');
        const ring = await hit.evaluate(el => ({ width: el.getBoundingClientRect().width, outline: getComputedStyle(el).outlineWidth, visible: el.matches(':focus-visible') }));
        assert(ring.visible && parseFloat(ring.outline) >= 2);
        assert(Math.abs(ring.width - await row.evaluate(el => el.clientWidth)) < 1.1);
        await hit.press('?');
        await page.getByRole('dialog').waitFor();
        await page.keyboard.press('Escape');
        await settle(page, watch);
        const link = row.getByRole('button', { name: other.name, exact: true });
        await link.click();
        await settle(page, watch);
        await page.getByRole('heading', { name: other.name, exact: true }).waitFor();
        assert.notEqual(await hit.getAttribute('aria-current'), 'true');
        await close();
        await link.focus();
        await link.press('Enter');
        await settle(page, watch);
        await page.getByRole('heading', { name: other.name, exact: true }).waitFor();
        await close();
        const main = page.locator('[data-deck-list="true"] > [class*="_cols_"] [data-oracle-id]').first();
        await scrollUntilVisible(page, main, VIEWPORTS[width]);
        await main.click({ modifiers: ['Control'] });
        await page.getByRole('toolbar', { name: 'Selected cards' }).waitFor();
        await page.getByRole('toolbar', { name: 'Selected cards' }).getByRole('button', { name: /^Clear/ }).click();
        assert.deepEqual(snap((await api('/api/decks/2')).state), snapshot);
        assert.equal((await axe(page)).length, 0);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
        const costlessRow = section.locator('[data-oracle-id="' + costless.oracle_id + '"]');
        await scrollUntilVisible(page, costlessRow, VIEWPORTS[width]);
        const noteBelowName = await costlessRow.evaluate(node => node.querySelector('[class*="_note_"]').getBoundingClientRect().top >= node.querySelector('[class*="_name_"]').getBoundingClientRect().bottom - 1);
        assert(noteBelowName, "a missing mana cost never moves its note into the name/mana/price row");
        await costlessRow.getByRole('button', { name: costless.name, exact: true }).focus();
        await page.keyboard.press('Space'); await settle(page, watch);
        await page.getByRole('heading', { name: costless.name, exact: true }).waitFor(); await close();
        await costlessRow.getByRole('button', { name: other.name, exact: true }).click(); await settle(page, watch);
        await page.getByRole('heading', { name: other.name, exact: true }).waitFor(); await close();
        await page.goto(origin + '/inbox');
        await settle(page, watch);
        const reason = page.getByRole('textbox', { name: /Reason for this proposal, optional/ }).first();
        await reason.fill('Unsaved visible-label check');
        assert.deepEqual(await reason.evaluate(el => Array.from(el.labels ?? []).map(label => label.textContent)), ['Reason (optional)']);
        assert.equal(await page.getByText('Reason (optional)', { exact: true }).isVisible(), true);
        assert.deepEqual(snap((await api('/api/decks/2')).state), snapshot);
        results.push({ width, blank_mana_price_clicks: true, enter_space_inspect: true, whole_row_focus_ring: ring, nested_note_pointer_keyboard: true, main_modifier_selection_preserved: true, assignments_and_membership_unchanged: true, no_slot_purpose_text: true, persistent_reason_label_while_typing: true, costless_note_below_name: true, costless_row_and_nested_note_activation: true });
        await context.close();
        console.log("Desktop QA width " + width + " passed");
    }
    const before = (await api('/api/decks/2')).state, priorLogs = new Set(before.log.map(l => l.id));
    const promoted = (await api('/api/decks/2/cards/' + card.oracle_id, 'PATCH', { maybe: false })).state, entry = promoted.log.find(l => !priorLogs.has(l.id));
    assert(entry);
    let c = promoted.cards.find(c => c.oracle_id === card.oracle_id);
    assert.equal(c.maybe, 0);
    assert.equal(c.slot_id, slots[0]);
    assert.deepEqual(c.secondary_slot_ids, [slots[1]]);
    const undone = await api('/api/decks/2/log/' + entry.id + '/undo', 'POST');
    assert.deepEqual(undone.skipped, []);
    c = undone.state.cards.find(c => c.oracle_id === card.oracle_id);
    assert.equal(c.maybe, 1);
    assert.equal(c.slot_id, slots[0]);
    assert.deepEqual(c.secondary_slot_ids, [slots[1]]);
    const baseBefore = (await api('/api/decks/2', 'GET', undefined, baseline)).state, baseLogs = new Set(baseBefore.log.map(l => l.id));
    const basePromoted = (await api('/api/decks/2/cards/' + card.oracle_id, 'PATCH', { maybe: false }, baseline)).state, baseEntry = basePromoted.log.find(l => !baseLogs.has(l.id));
    const baseUndone = await api('/api/decks/2/log/' + baseEntry.id + '/undo', 'POST', undefined, baseline);
    assert.deepEqual(snap(undone.state), snap(baseUndone.state));
    writeFileSync(output, JSON.stringify({ results, promotion_undo_preserve_primary_secondary_and_membership: true, post_undo_state_matches_baseline: true, baseline_maybe_note_clear_on_promotion_unchanged: true }, null, 2) + '\n');
    console.log(JSON.stringify({ results, promotion_undo: true }));
}
finally {
    await browser.close();
}
